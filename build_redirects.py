# -*- coding: utf-8 -*-
"""
בונה את קובץ ההפניות של נטליפיי.

הבעיה שהוא פותר: נטליפיי מגישה כל עמוד בשתי כתובות. גם
/guide-oyster וגם /guide-oyster.html מחזירים 200, וגוגל אינדקס
את שתיהן כשני עמודים נפרדים שמתחרים זה בזה. נמדד בפועל בנתוני
Search Console: אחד עשר עמודים מפוצלים, ובהם 21 אחוז מהחשיפות.

הפתרון: גרסת הכתובת ללא הסיומת היא הקנונית, כי זו הגרסה שנטליפיי
מגישה בפועל ושאליה מצביעים כל הקישורים הפנימיים. גרסת ה-html
מופנית אליה בהפניה קבועה.

סימן הקריאה בסוף כל שורה הוא קריטי. בלעדיו נטליפיי מגישה את
הקובץ שקיים בנתיב המבוקש ומתעלמת מההפניה, ולכן שום דבר לא היה קורה.

להרצה מחדש אחרי כל הוספה או מחיקה של עמוד:
    python3 build_redirects.py
"""
import glob, os

os.chdir(os.path.dirname(os.path.abspath(__file__)))

# 404 הוא עמוד השגיאה של נטליפיי ואסור להפנות אותו.
# admin נשאר כפי שהוא כדי לא לגעת בזרימת הכניסה לפאנל, וממילא הוא חסום ב-robots.
SKIP = {'404.html', 'admin.html'}

HEAD = """# נוצר אוטומטית על ידי build_redirects.py. אין לערוך ידנית.
#
# כל עמוד באתר מוגש על ידי נטליפיי בשתי כתובות, עם סיומת html ובלעדיה.
# הכתובת ללא הסיומת היא הקנונית, וזו שאליה מצביעים הקישורים הפנימיים
# והקנוניקל. השורות כאן מונעות מגרסת ה-html להתקיים ככתובת עצמאית.
#
# סימן הקריאה מכריח את ההפניה גם כשקיים קובץ בנתיב המקור. בלעדיו
# נטליפיי הייתה מגישה את הקובץ ומתעלמת מההפניה.

"""


def main():
    lines = []
    pages = sorted(glob.glob('*.html'))

    # דף הבית: index.html מפנה לשורש
    lines.append('/index.html    /    301!')

    n = 0
    for f in pages:
        if f in SKIP or f == 'index.html':
            continue
        bare = '/' + f[:-5]
        lines.append('%-46s %-42s 301!' % ('/' + f, bare))
        n += 1

    """
    קבצים תפעוליים. סקריפטי הבנייה שייכים לריפו ולא לאתר הציבורי.
    נטליפיי לא תומכת בתבנית עם כוכבית באמצע נתיב כמו ‎/*.py, ולכן
    כל קובץ נחסם בנתיב מפורש. הרשימה נגזרת מהדיסק, כך שסקריפט
    חדש ייחסם אוטומטית בבנייה הבאה.
    """
    ops = sorted(glob.glob('*.py'))
    lines.append('')
    lines.append('# קבצים תפעוליים, חסומים מהגשה ציבורית')
    for f in ops:
        lines.append('%-46s %-42s 404!' % ('/' + f, '/404.html'))

    body = HEAD + '\n'.join(lines) + '\n'
    open('_redirects', 'w', encoding='utf-8').write(body)

    print('נוצר _redirects')
    print('  עמודים שהופנו: %d' % n)
    print('  לא הופנו במכוון: %s' % ', '.join(sorted(SKIP)))
    print('  דף הבית: /index.html מפנה לשורש')


main()
